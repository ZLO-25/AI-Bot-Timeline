export function paretoOf(points: AaiiPoint[]) {
  return points
    .filter(
      (point) =>
        !points.some(
          (other) =>
            other.id !== point.id &&
            other.aaii >= point.aaii &&
            other.cost <= point.cost &&
            (other.aaii > point.aaii || other.cost < point.cost),
        ),
    )
    .sort((a, b) => a.cost - b.cost);
}
